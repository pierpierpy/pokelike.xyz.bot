"""Formatting benchmark results as terminal tables and Markdown for the README.

This module handles presentation only. All data comes from results.py and
versions.py.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ...arena.bench import STANDARD_SEEDS
from ...logging import LEARN_K
from ...shared.tables import show_region as _show_region
from .pricing import cost
from .versions import (_bench, cross_run_memory, settings_text, slug,
                       version_settings, versions)

README_BEGIN_MARK = "<!-- BEGIN llm-bench"
README_BEGIN = (f"{README_BEGIN_MARK}: generated by "
                "`pokelike model board --harness <v>`, do not edit by hand -->")
README_END = "<!-- END llm-bench -->"


def format_table(version: str, price: dict[str, dict[str, float]] | None = None) -> str:
    """Formats the standings for terminal output."""
    import sys

    from .results import stats_by_settings

    # Looked up through the package so that tests can monkeypatch `L.load`.
    _pkg = sys.modules[__package__]
    rows = [row for d in _pkg.load(version) for row in stats_by_settings(d, version)]
    rows = [r for r in rows if r.get("runs")]
    if not rows:
        return ""
    rows.sort(key=lambda r: -r["badges_mean"])
    money = bool(price)
    # Learn column only shown for harnesses with cross-run memory.
    learns = cross_run_memory(version)
    # The region column is shown only when at least one row is not kanto.
    show_region = _show_region(rows)
    # The settings column appears when the version has a knob of its own, e.g. two
    # rows for the same model under `reasoning=low` and `reasoning=high`. A row
    # that overrode nothing shows the default rather than a blank.
    show_settings = bool(version_settings(version))
    # The column is sized to its widest value, since two knobs at once
    # (`notes=40,reasoning=minimal`) overflow any fixed width and run the
    # neighbouring numbers together.
    swid = (max((len(settings_text(version, r.get("settings"))) for r in rows),
                default=0) + 2) if show_settings else 0
    head = (f"{'model':<34}{'passes':>7}{'runs':>6}"
            + (f"{'region':>9}" if show_region else "")
            + (f"{'set':>{swid}}" if show_settings else "")
            + f"{'badges~':>9}{'±sem':>7}"
            f"{'med':>5}{'best':>6}{'won':>5}{'Elite4':>7}"
            + (f"{'learn':>8}{'notes':>7}" if learns else "")
            + f"{'tok in/run':>11}{'tok out/run':>12}{'fallback':>9}"
            + (f"{'$':>8}{'$/run':>9}" if money else ""))
    out = [f"models on harness {version}, {len(STANDARD_SEEDS)} seeds a pass. "
           "Harnesses are not comparable.",
           "", head, "-" * len(head)]
    for r in rows:
        usd = cost(r["tokens_in_per_run"] * r["runs"], r["tokens_out_per_run"] * r["runs"],
                   (price or {}).get(r["model"])) if money else None
        lc = r.get("learning") or {}
        settings_str = settings_text(version, r.get("settings"))
        out.append(
            f"{str(r['model'])[:33]:<34}{r['passes']:>7}{r['runs']:>6}"
            + (f"{(r.get('region') or 'kanto'):>9}" if show_region else "")
            + (f"{settings_str or '-':>{swid}}" if show_settings else "")
            + f"{r['badges_mean']:>9}{r['badges_sem']:>7}{r['badges_median']:>5}"
            f"{r['badges_best']:>6}{r.get('won', 0):>5}{r.get('elite4', 0):>7}"
            + ((f"{lc['delta']:>+8.2f}" if lc.get("delta") is not None else f"{'-':>8}")
               + f"{r.get('notes_kept') if r.get('notes_kept') is not None else '-':>7}"
               if learns else "")
            + f"{r['tokens_in_per_run']:>11}"
            f"{r['tokens_out_per_run']:>12}{r['fallback_rate']:>9}"
            + (f"{usd:>8.2f}{usd / r['runs']:>9.4f}" if usd is not None
               else (f"{'-':>8}{'-':>9}" if money else ""))
            + ("  <- harness or render changed since this ran" if r.get("stale") else "")
            + ("  <- fallback over 0.1: measuring the harness, not the model"
               if r["fallback_rate"] > 0.1 else "")
        )
    legend = ["±sem: rows within twice it are tied"]
    if learns:
        legend.append("learn: last 10 runs of a pass minus its first 10")
    if money:
        legend.append("$: OpenRouter prices fetched now, never stored")
    out += ["-" * len(head), "   ".join(legend)]
    return "\n".join(out)


def markdown_table(version: str,
                   price: dict[str, dict[str, float]] | None = None) -> str:
    """Formats the standings as a Markdown table for the README."""
    from .results import load, stats_by_settings

    rows = [row for d in load(version) for row in stats_by_settings(d, version)]
    rows = [r for r in rows if r.get("runs")]
    if not rows:
        return f"_No models measured under harness `{version}` yet._"
    rows.sort(key=lambda r: -r["badges_mean"])
    learns = cross_run_memory(version)
    # The column appears when the version has a knob of its own, whether or not
    # any row overrode it, so a default is stated rather than left blank.
    show_settings = bool(version_settings(version))
    scol, shdr = ("| set ", "|---") if show_settings else ("", "")
    lcol, lhdr = ("| learn | notes ", "|--:|--:") if learns else ("", "")
    out = [f"### Harness `{version}`", "",
           f"| # | model {scol}| passes | runs | badges~ | ±sem | best | Elite4 {lcol}| tok in/run "
           f"| tok out/run | fallback | $ | $/run |",
           f"|--:|---{shdr}|--:|--:|--:|--:|--:|--:{lhdr}|--:|--:|--:|--:|--:|"]
    for i, r in enumerate(rows, 1):
        flag = " ⚠︎" if r.get("stale") else ""
        usd = cost(r["tokens_in_per_run"] * r["runs"],
                   r["tokens_out_per_run"] * r["runs"], (price or {}).get(r["model"]))
        lc = r.get("learning") or {}
        settings_cell = ""
        if show_settings:
            settings_cell = f"| `{settings_text(version, r.get('settings'))}` "
        cell = ""
        if learns:
            d = lc.get("delta")
            cell = (f"| {'-' if d is None else f'{d:+.2f}'} "
                    f"| {r.get('notes_kept') if r.get('notes_kept') is not None else 'n/a'} ")
        each = None if usd is None else usd / r["runs"]
        out.append(
            f"| {i} | `{r['model']}`{flag} {settings_cell}| {r['passes']} | {r['runs']} | "
            f"**{r['badges_mean']}** | {r['badges_sem']} | {r['badges_best']} | "
            f"{r.get('elite4', 0)} {cell}| "
            f"{r['tokens_in_per_run']} | {r['tokens_out_per_run']} | "
            f"{r['fallback_rate']} | {'n/a' if usd is None else f'{usd:.2f}'} "
            f"| {'n/a' if each is None else f'{each:.4f}'} |")
    out += ["", "`Elite4` is how many of this row's runs beat an Elite Four, "
                "summed. A single-region run is 1 if it ended on the win screen, "
                "0 otherwise; a multi-region campaign run counts every region it "
                "cleared, even one it later died in."]
    if learns:
        out += ["", f"`learn` is the last {LEARN_K} runs of a pass minus its "
                    f"first {LEARN_K}, in the order played. This harness lets "
                    "the model keep notes between runs, so that column is what it "
                    "exists to measure. `badges~` is a mean over a learning curve "
                    "here."]
    if show_settings:
        out += ["", "`set` lists the knobs this harness version has of its own, "
                    "with the value each pass ran under. A pass that passed no "
                    "`--set` shows the harness default, so every row states what "
                    "it ran with. The flags every version shares are left out "
                    "because they say nothing about which question a row answers. "
                    "Two rows for the same model with different `set` values are "
                    "two different questions, not two samples of the same one."]
    return "\n".join(out)


def _pass_head(version: str, doc: dict, p: dict, played: list) -> list[str]:
    """Returns the heading lines shared by both kinds of page."""
    sett = ",".join(f"{k}={v}" for k, v in (p.get("settings") or {}).items())
    head = f"## Pass `{p.get('stamp') or 'unstamped'}`"
    if sett:
        head += f", `--set {sett}`"
    mean = sum(r.get("badges") or 0 for r in played) / len(played)
    return [head, "",
            f"The pass played {len(played)} runs and averaged {mean:.2f} badges.", ""]


def _played(p: dict) -> list:
    """Returns a pass's runs in the order they were played."""
    return sorted(p.get("runs") or [],
                  key=lambda r: (r.get("order") is None, r.get("order"), r.get("seed")))


def _badges(n: int) -> str:
    """Returns the count with a noun that agrees with it."""
    return f"{n} badge" if n == 1 else f"{n} badges"


def notebook_page(version: str, doc: dict) -> str:
    """Formats the notes one model kept under one harness version, as Markdown.

    The page reports what the model wrote down rather than what it learned. A
    notebook holds whatever the model chose to keep, which mixes what it saw in
    play with what it already knew before the benchmark started, and the two
    cannot be told apart by reading it.

    Everything here comes from the recorded result, so a page can be regenerated
    for any pass ever recorded, including one whose logs are long gone.
    """
    model = doc.get("model") or "unknown"
    out = [f"# {model} under harness `{version}`", "",
           "This page holds the notes the model kept while it played. A note is "
           "whatever the model chose to write down through its `remember` and "
           "`revise` tools, so the notebook records what the model thought worth "
           "keeping. Some of it was learned in play and some of it the model "
           "already knew, and the notebook does not distinguish them.", "",
           "The route the model planned for each run is on its own page under "
           "`plans/`.", ""]

    for p in doc.get("passes", []):
        played = _played(p)
        if not played:
            continue
        out += _pass_head(version, doc, p, played)
        final = played[-1].get("notebook") or []
        if final:
            out += ["### The notebook at the end", ""]
            out += [f"{i}. {n}" for i, n in enumerate(final, 1)]
            out += [""]
        # How the notebook grew, sampled so a fifty-run pass stays readable.
        marks = [r for i, r in enumerate(played) if i % 10 == 0 or r is played[-1]]
        if len(marks) > 1:
            out += ["### How it grew", "",
                    "| run | seed | notes kept | badges |", "|--:|--:|--:|--:|"]
            for r in marks:
                out.append(f"| {r.get('order') or '?'} | {r.get('seed')} | "
                           f"{len(r.get('notebook') or [])} | {r.get('badges')} |")
            out += [""]
    return "\n".join(out)


def plan_page(version: str, doc: dict) -> str:
    """Formats the route one model planned for every run, as Markdown.

    A plan is what the model laid out for the map it was standing on, rewritten
    whenever it chose to call the `plan` tool again, and the page keeps one entry
    per run so a reader can follow how the intention changed over a pass.
    """
    model = doc.get("model") or "unknown"
    out = [f"# {model} under harness `{version}`, the routes it planned", "",
           "A plan is the route the model laid out for the map it was standing on, "
           "through its `plan` tool. One entry per run, in the order the runs were "
           "played.", "",
           "The notes the model kept are on its own page under `notebooks/`.", ""]

    for p in doc.get("passes", []):
        played = _played(p)
        if not played:
            continue
        out += _pass_head(version, doc, p, played)
        best = max(played, key=lambda r: (r.get("badges") or 0, -(r.get("steps") or 0)))
        out += [f"Its best run was seed {best.get('seed')} at "
                f"{_badges(best.get('badges') or 0)}.", ""]
        for r in played:
            if not r.get("plan"):
                continue
            mark = " (best)" if r is best else ""
            out += [f"**Run {r.get('order') or '?'}, seed {r.get('seed')}, "
                    f"{_badges(r.get('badges') or 0)}{mark}**", "",
                    "> " + str(r.get("plan")).replace("\n", "\n> "), ""]
    return "\n".join(out)


def write_pages(version: str) -> dict[str, list[Path]]:
    """Writes the notebook and plan pages for every model measured under a version.

    Versions that keep no notes between runs get no directories, because a page of
    nothing invites the reader to wonder what went missing.
    """
    from .results import load

    if not cross_run_memory(version):
        return {}
    docs = [d for d in load(version) if d.get("passes")]
    if not docs:
        return {}
    written: dict[str, list[Path]] = {"notebooks": [], "plans": []}
    for kind, builder in (("notebooks", notebook_page), ("plans", plan_page)):
        out = _bench() / version / kind
        out.mkdir(parents=True, exist_ok=True)
        for d in docs:
            path = out / f"{slug(d.get('model') or 'unknown')}.md"
            path.write_text(builder(version, d) + "\n", encoding="utf-8")
            written[kind].append(path)
    return written


def write_readme(price: dict[str, dict[str, float]] | None = None) -> Path:
    """Regenerates the standings block in llm-bench/README.md, newest harness first."""
    path = _bench() / "README.md"
    blocks = [markdown_table(v, price) for v in reversed(versions())]
    body = "\n\n".join(blocks) if blocks else "_Nothing measured yet._"
    generated = f"{README_BEGIN}\n\n{body}\n\n{README_END}"
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        # The match uses the marker prefix so the marker stays findable even if
        # the command name changes.
        i, j = text.find(README_BEGIN_MARK), text.find(README_END)
        if i != -1 and j > i:
            path.write_text(text[:i] + generated + text[j + len(README_END):],
                            encoding="utf-8")
        else:
            # The markers were not found, so the generated block is appended.
            path.write_text(text.rstrip("\n") + "\n\n" + generated + "\n",
                            encoding="utf-8")
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generated + "\n", encoding="utf-8")
    return path
