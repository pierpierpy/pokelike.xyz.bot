class LLMError(RuntimeError):
    """A recoverable error on one model call. The harness falls back and plays on."""


class LLMConfigError(LLMError):
    """The setup is wrong and every call will fail the same way.

    Raised for bad tokens, unknown models, or invalid endpoints. These errors stop
    the run rather than falling back, because falling back would file a full run of
    backup-heuristic moves as an LLM result.
    """


class LLMBudgetError(LLMError):
    """The run asked for more tokens than the bot allowed itself.

    Only raised when TOKEN_BUDGET is set. The error stops the run rather than
    silently consuming an unbounded amount.
    """


