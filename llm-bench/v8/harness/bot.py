    # --------------------------------------------------------------- decision

    def reason(self) -> str:
        return self._last_why

    def reorder(self, state: dict[str, Any]) -> tuple[int, int] | None:
        """Decides the lead in the same model call as the move.

        The run loop calls reorder() before act(), so the whole turn is decided
        in one HTTP call. The chosen action is cached and act() returns it.
        Only offered on the map screen, because elsewhere the options are the
        team itself and reordering would change what an index means.
        """
        self._pending = None
        if state.get("screen") != "map-screen" or not state.get("can_reorder"):
            return None
        try:
            index, why, lead = self._agentic_round(state, allow_lead=True)
        except LLMConfigError:
            raise
        except Exception:  # noqa: BLE001, handled again and counted in choose
            return None
        team = state.get("team") or []
        if lead is None or not 0 < lead < len(team):
            self._pending = (state.get("steps"), index, why)
            return None
        # The lead is folded into the pending explanation because act() overwrites
        # _last_why.
        why = f"lead {team[lead]['name']} | {why}"
        self._pending = (state.get("steps"), index, why)
        return (0, lead)

    def act(self, state: dict[str, Any]) -> int:
        self.turns += 1
        # Kept because the engine empties its state at game over, so this is the
        # last place the badges and the team are still readable.
        self._last_state = state
        n = len(state["actions"])
        # The turn was already decided in reorder(). The `steps` guard prevents
        # replaying a cached index against a different turn.
        if self._pending and self._pending[0] == state.get("steps"):
            _, index, why = self._pending
            self._pending = None
            if isinstance(index, int) and 0 <= index < n:
                return self._commit(state, index, why)
        try:
            index, why, _ = self._agentic_round(state)
        except (LLMConfigError, LLMBudgetError):
            # These errors are not recoverable because every later call fails
            # identically, or the run has spent what it was allowed. Stopping is
            # better than quietly handing the rest of the run to the backup
            # heuristic and filing the result as an LLM run.
            raise
        except Exception as e:  # noqa: BLE001, a transient failure must not end the run
            return self._run_fallback(state, f"{type(e).__name__}: {e}"[:80])

        if not isinstance(index, int) or not 0 <= index < n:
            return self._run_fallback(state, f"model returned index {index}")
        return self._commit(state, index, why)

    def _commit(self, state: dict[str, Any], index: int, why: str) -> int:
        self._last_why = why
        self.journal.append(self._journal_entry(state, index, why))
        # A value of -1 means keep every turn (no trimming).
        if self.memory >= 0:
            self.journal = self.journal[-self.memory:]
        if self.verbose:
            print(f"   [llm] -> [{index}] {why[:100]}")
        return index

    def _journal_entry(self, state: dict[str, Any], index: int, why: str) -> str:
        """Builds one journal line from the factual action in state plus the model's sentence.

        The action comes from state["actions"][index] (harness data, independent of
        the model's own words). The model's sentence is kept so the model can notice
        repeated patterns, and it is labelled as opinion.
        """
        actions = state.get("actions") or []
        act = actions[index] if 0 <= index < len(actions) else {}
        if act.get("kind") == "node":
            did = f"node {act.get('id', '?')} ({act.get('node', 'node')})"
            if act.get("tooltip"):
                did += f", {act['tooltip']}"
        else:
            did = str(act.get("label") or act.get("id") or "action")
        said = " ".join(str(why or "").split())[:200]
        return (f"step {state.get('steps')}: [{index}] {did}\n"
                f"    it said: {said or '(nothing)'}")

    def _run_fallback(self, state: dict[str, Any], reason: str) -> int:
        self.fallbacks += 1
        self._last_why = f"(fell back: {reason})"
        if self.verbose:
            print(f"   [llm] fallback: {reason}")
        return self.fallback_move(state)

    def fallback_move(self, state: dict[str, Any]) -> int:
        """Backup choice when the model fails to produce a valid move.

        The heuristic prefers healing when hurt, and otherwise widening the team.
        """
        actions = state["actions"]
        team = state.get("team") or []
        hurt = [p for p in team if p["max_hp"] and p["hp"] / p["max_hp"] < 0.4]

        order = ["pokecenter", "catch", "item"] if hurt else ["catch", "item", "pokecenter"]
        for kind in order:
            for i, a in enumerate(actions):
                if a.get("node") == kind:
                    return i
        return 0

    # ---------------------------------------------------------- agentic loop

    def _agentic_round(self, state: dict[str, Any],
                       allow_lead: bool = False) -> tuple[int, str, int | None]:
        """One turn of thinking. Returns (action index, reason, lead or None)."""
        lead: int | None = None
        # The last SCRATCH_TURNS exchanges come along verbatim so the model can
        # build on its own reasoning across turns. The count is bounded to keep
        # request size manageable; older turns are summarised in the journal.
        history: list[dict[str, Any]] = [m for turn in self.scratch for m in turn]
        messages: list[dict[str, Any]] = [
            {"role": "system", "content": self.system},
            *history,
            {"role": "user", "content": self._situation(state)},
        ]
        # This turn's exchanges are kept separately so the system prompt and
        # older turns are not duplicated into the scratchpad.
        this_turn: list[dict[str, Any]] = [messages[-1]]

        for _ in range(self.max_rounds):
            msg = self.call_model(messages)
            calls = msg.get("tool_calls") or []
            if not calls:
                # The model called no tool, so try to extract an index from prose.
                index = self._index_from_text(msg.get("content") or "", len(state["actions"]))
                if index is not None:
                    return index, "(read from prose)", lead
                raise LLMError("the model called no tool")

            spoke = {"role": "assistant", "content": msg.get("content") or "",
                     "tool_calls": calls}
            messages.append(spoke)
            this_turn.append(spoke)

            for c in calls:
                name = c["function"]["name"]
                try:
                    args = json.loads(c["function"].get("arguments") or "{}")
                except json.JSONDecodeError:
                    args = {}
                self._note_call(name, args)

                if name == "play":
                    # The turn ends here. All tool calls (including play itself and
                    # any after it) are answered before storing, so the scratchpad
                    # contains a valid conversation.
                    answered = {m.get("tool_call_id") for m in this_turn
                                if m.get("role") == "tool"}
                    for other in calls:
                        if other["id"] in answered:
                            continue
                        this_turn.append({
                            "role": "tool", "tool_call_id": other["id"],
                            "content": (f"played index {args.get('index')}."
                                        if other is c else
                                        "not run: the turn ended at play().")})
                    self._remember_turn(this_turn)
                    return args.get("index"), str(args.get("why", "")), lead

                if name == "set_lead":
                    # The lead choice is recorded but not applied here; the run
                    # loop performs the swap.
                    want = args.get("index")
                    if allow_lead and isinstance(want, int):
                        lead = want
                        reply = f"ok, slot {want} will lead. Now call play()."
                    else:
                        reply = ("not available on this screen: the options here are "
                                 "your team, so reordering would change what an index "
                                 "means. Call play().")
                    answer = {"role": "tool", "tool_call_id": c["id"], "content": reply}
                    messages.append(answer)
                    this_turn.append(answer)
                    continue

                answer = {"role": "tool", "tool_call_id": c["id"],
                          "content": self.answer_tool(name, args, state)}
                messages.append(answer)
                this_turn.append(answer)

        # All rounds are exhausted. The exchange is kept so the next turn can see
        # what happened rather than repeating the same calls.
        self._remember_turn(this_turn)
        raise LLMError(f"no call to play() within {self.max_rounds} rounds")

    def _remember_turn(self, turn: list[dict[str, Any]]) -> None:
        """Adds one exchange to the scratchpad, replacing the screen with a placeholder.

        The screen is replaced because it is stale by the next turn and the current
        screen is already in the fresh user message. The model's reasoning and the
        tool replies stay because they cannot be reconstructed.
        """
        kept = [
            {"role": "user",
             "content": "[the screen you were shown that turn, since changed]"}
            if m.get("role") == "user" else m
            for m in turn
        ]
        self.scratch.append(kept)
        self.scratch = self.scratch[-self.SCRATCH_TURNS:] if self.SCRATCH_TURNS else []

    # ------------------------------------------------------------------ tools

    def tools(self) -> list[dict[str, Any]]:
        """Returns the shared eight tools plus EXTRA_TOOLS, in OpenAI function-calling form.

        Override this method to change the set, but the `play` tool must survive or
        every turn falls back.

        The budgets are substituted here as well as in the prompt, because a tool
        description is text the model reads and a limit it is not told about is a
        limit it cannot write to.
        """
        subs = {"%NOTE_CHARS%": str(self.note_chars),
                "%PLAN_CHARS%": str(self.plan_chars),
                "%NOTES%": str(self.notes_max)}

        def filled(text: str) -> str:
            for k, v in subs.items():
                text = text.replace(k, v)
            return text

        out = []
        for t in (*TOOLS, *self.EXTRA_TOOLS):
            fn = t.get("function") or {}
            if "%" not in str(fn.get("description", "")) and "%" not in str(fn):
                out.append(t)
                continue
            copy = {**t, "function": {**fn}}
            if copy["function"].get("description"):
                copy["function"]["description"] = filled(copy["function"]["description"])
            props = ((copy["function"].get("parameters") or {}).get("properties") or {})
            if props:
                copy["function"] = {**copy["function"],
                                    "parameters": {**copy["function"]["parameters"],
                                                   "properties": {
                                       k: ({**v, "description": filled(v["description"])}
                                           if isinstance(v, dict) and v.get("description")
                                           else v)
                                       for k, v in props.items()}}}
            out.append(copy)
        return out

    def answer_tool(self, name: str, args: dict[str, Any], state: dict[str, Any]) -> str:
        """Answers one tool call; the return value is shown to the model.

        Override this method for custom tools and call super() for the shared ones.
        An unknown name gets a message rather than an exception so the model can
        continue.
        """
        if name == "team_details":
            return render.team_view(state.get("team")) or "(empty team)"
        if name == "what_lies_ahead":
            return self._exits(state)
        if name in ("remember", "revise", "forget"):
            return self._remember(name, args)

        if name == "plan":
            # The plan is truncated rather than refused because a short plan is
            # still useful.
            route = str(args.get("route") or "").strip().replace("\n", " ")
            if not route:
                return "nothing to plan: `route` was empty."
            had, self.plan = bool(self.plan), route[: self.plan_chars]
            return (("plan replaced. " if had else "plan noted. ")
                    + "You will see it every turn until you change it.")
        return f"unknown tool: {name}"

    # --------------------------------------------------------------- memory

    def _remember(self, verb: str, args: dict[str, Any]) -> str:
        """Handles the remember, revise, and forget verbs.

        Every reply states the current count so the model knows how full its
        notebook is. Notes are truncated to NOTE_CHARS rather than rejected.
        """
        note = str(args.get("note") or "").strip().replace("\n", " ")
        note = note[: self.note_chars]

        if verb == "remember":
            if not note:
                return self._refused("empty note",
                                     "nothing to remember: `note` was empty.")
            if len(self.notebook) >= self.notes_max:
                return self._refused(
                    "notes full",
                    f"your notes are full ({self.notes_max}). Use `revise` to "
                    f"improve one or `forget` to make room, then try again.")
            self.notebook.append(note)
            self._kept()
            return (f"noted as [{len(self.notebook)}]. "
                    f"{len(self.notebook)}/{self.notes_max} notes used.")

        # The revise and forget verbs address notes by the 1-based number shown
        # to the model.
        try:
            i = int(args.get("id"))
        except (TypeError, ValueError):
            return self._refused(
                "no id",
                f"`id` must be a number between 1 and {len(self.notebook)}.")
        if not 1 <= i <= len(self.notebook):
            return self._refused(
                "no such note",
                f"there is no note [{i}]. You have {len(self.notebook)}: "
                f"use a number between 1 and {len(self.notebook)}.")

        if verb == "forget":
            gone = self.notebook.pop(i - 1)
            self._kept(dropped=gone)
            return (f"forgotten: {gone[:60]}. "
                    f"{len(self.notebook)}/{self.notes_max} notes used, and they have "
                    f"been renumbered.")
        if not note:
            return self._refused("empty note",
                                 "nothing to revise it to: `note` was empty.")
        was = self.notebook[i - 1]
        self.notebook[i - 1] = note
        self._kept(was=was)
        return (f"note [{i}] rewritten. "
                f"{len(self.notebook)}/{self.notes_max} notes used.")

    # ------------------------------------------------------------ the record

    def _note_call(self, name: str, args: dict[str, Any]) -> None:
        """Records one tool call before execution.

        This captures play, set_lead, and invented names too, since those calls
        never reach answer_tool().
        """
        entry: dict[str, Any] = {"tool": name}
        for k in ("index", "id", "slot", "note", "route", "why"):
            v = args.get(k)
            if v not in (None, ""):
                entry[k] = v if not isinstance(v, str) else v[: self.note_chars]
        self.tool_log.append(entry)

    def _kept(self, **what: Any) -> None:
        """Marks the call just recorded as having changed the notes."""
        if self.tool_log:
            self.tool_log[-1]["kept"] = len(self.notebook)
            self.tool_log[-1].update(
                {k: str(v)[: self.note_chars] for k, v in what.items() if v})

    def _refused(self, why: str, reply: str) -> str:
        """Marks the call as refused in the tool log and returns the reply to the model."""
        if self.tool_log:
            self.tool_log[-1]["refused"] = why
            self.tool_log[-1]["kept"] = len(self.notebook)
        return reply

    def tool_calls_made(self) -> list[dict[str, Any]]:
        """Returns and clears all tool calls since the last drain.

        The list is drained per decision rather than per turn because reorder()
        may also call the model, and those calls belong to the same decision.
        """
        out, self.tool_log = self.tool_log, []
        return out

    def _memory_block(self) -> list[str]:
        """Returns the notes numbered from 1, matching the ids that revise/forget accept.

        The heading says who wrote them rather than what they are worth. Under v7 it
        read "WHAT YOU HAVE LEARNED", and a model reads that as a list of established
        facts: one wrote all eight Johto gym types into its notebook while still
        playing Kanto, from what it already knew rather than from anything it had
        seen, and carried them for fifty runs without once revisiting them.
        """
        if not self.notebook:
            return ["", "WHAT YOU HAVE WRITTEN DOWN SO FAR: nothing yet. Use "
                    "`remember` when you learn something that will still be true "
                    "next run."]
        return ["", f"WHAT YOU WROTE DOWN (your own notes, kept across runs, "
                    f"{len(self.notebook)}/{self.notes_max}). You wrote these, so any "
                    f"of them can be wrong:",
                *(f"  [{i}] {n}" for i, n in enumerate(self.notebook, 1))]

    def _history_block(self) -> list[str]:
        """Returns what came of the runs before this one, shown next to the notes.

        The two belong together, because those runs were played while these notes
        were being carried. Read apart, neither says anything about the other.
        """
        if not self.run_history:
            return ["", "BEFORE THIS RUN: nothing. This is your first run."]
        n = len(self.run_history)
        return ["", f"WHAT CAME OF YOUR LAST {n} RUN{'' if n == 1 else 'S'} "
                    f"(oldest first). You were carrying the notes above while these "
                    f"were played:",
                *(f"  {e}" for e in self.run_history)]

    def finish(self, state: dict[str, Any], score: dict[str, Any] | None) -> None:
        """Records what the run that just ended leaves for the next one.

        The runner calls this once a run is over, and the model writes the entry
        itself, so what carries forward is what the model thinks cost it the run
        rather than the figures it can already see. One extra call per run pays for
        that. The figures are the fallback, because a run left unaccounted for is
        worse than a run accounted for plainly.

        The badges are read from the last turn this bot saw rather than from
        `state`, because the engine empties its state at game over and hands back an
        empty team and no badges however far the run went.

        Guarded, because a run that reaches here has already been played and
        counted. Losing the entry costs a line of context; letting an exception out
        would cost the run.
        """
        seen = self._last_state or {}
        run = seen.get("run") or {}
        badges = run.get("badges", seen.get("badges", 0))
        where = run.get("map", seen.get("map", 0))
        plain = (f"seed {self.seed}: {badges} badge{'' if badges == 1 else 's'}, "
                 f"{self.turns} turns, reached map {where}")
        entry = plain
        try:
            reply = self.call_model([
                {"role": "system", "content": PROMPT_SUMMARY_SYSTEM},
                {"role": "user", "content": PROMPT_SUMMARY_USER % {
                    "seed": self.seed, "badges": badges, "turns": self.turns,
                    "map": where}},
            ], tools=[])       # prose, so no tool is offered
            said = (reply.get("content") or "").strip().replace("\n", " ")
            if said:
                entry = f"seed {self.seed} ({badges} badges): {said}"
        except Exception as e:                       # noqa: BLE001 (see the docstring)
            if self.verbose:
                print(f"   [llm] the run summary was not written: {type(e).__name__}: {e}")
        self.run_history.append(self._cut(entry))
        del self.run_history[: -self.RUN_SUMMARY_KEEP]

    def _cut(self, entry: str) -> str:
        """Returns the entry inside its budget, ending on a full sentence when it can.

        A hard cut lands mid word, and the result is read by the model at every turn
        of every later run, so the budget is spent on whole sentences and the rest is
        dropped.
        """
        if len(entry) <= self.RUN_SUMMARY_CHARS:
            return entry
        head = entry[: self.RUN_SUMMARY_CHARS]
        stop = max(head.rfind(". "), head.rfind("! "), head.rfind("? "))
        return head[: stop + 1] if stop > self.RUN_SUMMARY_CHARS // 2 else head

    def _plan_block(self) -> list[str]:
        """Returns the current plan or the invitation to write one, shown every turn."""
        if not self.plan:
            return ["", "YOUR PLAN FOR THIS MAP: none yet. Use `plan` to write the "
                    "route you mean to take, before the first choice closes options "
                    "you wanted."]
        return ["", f"YOUR PLAN FOR THIS MAP (yours, change it with `plan`): "
                    f"{self.plan}"]

    # ---------------------------------------------------------------- context

    def render_state(self, state: dict[str, Any]) -> str:
        """Returns what the model reads each turn; this is the hook for changing the view.

        The method reads STATE_VIEW. Override this method for anything the four
        settings do not cover. The harness adds the journal and instruction line
        around the return value.
        """
        spec = self.state_view
        if isinstance(spec, str) and spec == "screen":
            return render.screen(state)
        if isinstance(spec, str) and spec in ("json", "both"):
            raw = json.dumps(state, separators=(",", ":"))
            if spec == "json":
                return raw
            return f"{render.screen(state)}\n\nTHE SAME STATE, IN FULL:\n{raw}"
        if isinstance(spec, (list, tuple)):
            missing = [k for k in spec if k not in state]
            if missing:
                # Some keys can be absent on certain screens (e.g. `map` during a
                # battle).
                if self.verbose:
                    print(f"   [llm] STATE_VIEW: no {', '.join(missing)} on this screen")
            return json.dumps({k: state[k] for k in spec if k in state},
                              separators=(",", ":"))
        raise LLMConfigError(
            f"STATE_VIEW is {spec!r}. Use 'screen', 'json', 'both', a list of "
            f"state keys, or override view(state) yourself."
        )

    def view_name(self) -> str:
        """Returns the setting to record, or 'custom' if `view` was replaced."""
        if type(self).render_state is not HarnessV8.render_state:
            return "custom"
        return self.state_view if isinstance(self.state_view, str) else \
            "keys:" + ",".join(self.state_view)

    def _situation(self, state: dict[str, Any]) -> str:
        """Builds the full user message from the rendered state, notes, plan, journal, and instruction.

        This is not the hook for changing the view (that is render_state). The
        journal and index instruction must always be present.
        """
        parts = [self.render_state(state)]
        # Notes come before the journal because cross-run lessons outrank recent
        # turns.
        parts += self._memory_block()
        parts += self._history_block()
        parts += self._plan_block()
        # The region summary is shown until this region's journal has turns of
        # its own.
        journal = self.journal
        if self._opening and not journal:
            journal = [f"LAST REGION: {self._opening}"]
        if journal:
            parts += [
                "",
                "WHAT YOU DID, AND WHAT YOU SAID AT THE TIME.",
                "The action on each first line is the game's record. The sentence "
                "under it is your own from that turn: it is what you meant to do, "
                "not something that has been verified since.",
                *(f"  {r}" for r in journal),
            ]
        parts += [
            "",
            f"Pick an index between 0 and {len(state['actions']) - 1} and call play().",
        ]
        return "\n".join(parts)

    def _exits(self, state: dict[str, Any]) -> str:
        """Returns where each legal action leads, by reading the map's edges."""
        m = state.get("map")
        if not m:
            return "You are not on the map: this choice opens or closes no paths."
        by_id = {n["id"]: n for n in m["nodes"]}
        rows = []
        for i, a in enumerate(state["actions"]):
            if a.get("kind") != "node":
                rows.append(f"  [{i}] {a.get('label', '')[:60]}")
                continue
            after = [by_id[t]["kind"] for f, t in m["edges"] if f == a["id"] and t in by_id]
            follows = ", ".join(sorted(after)) if after else "nothing (end of map)"
            rows.append(f"  [{i}] {a['node']:<12} -> leads to: {follows}")
        return "Exits on the next layer:\n" + "\n".join(rows)

    # ------------------------------------------------------------------- HTTP

    def call_model(self, messages: list[dict[str, Any]],
                   tools: list[dict[str, Any]] | None = None) -> dict[str, Any]:
        if self.token_budget and self.tokens_used >= self.token_budget:
            raise LLMBudgetError(
                f"run spent {self.tokens_used} tokens, budget is {self.token_budget}"
            )
        body = json.dumps({
            "model": self.model,
            "messages": messages,
            # Passing `tools=[]` asks the model for prose only, while None means
            # this bot's usual set.
            "tools": self.tools() if tools is None else tools,
            "tool_choice": "auto",
            "max_tokens": self.max_tokens,
            "temperature": self.temperature,
            # Sent as best effort, but most providers ignore the seed field.
            # Nothing depends on it.
            "seed": self.seed,
            **({"reasoning_effort": self.reasoning_effort}
               if self.reasoning_effort is not None else {}),
        }).encode("utf-8")

        req = urllib.request.Request(
            f"{self.endpoint}/v1/chat/completions",
            data=body,
            headers={
                "Authorization": f"Bearer {self.token}",
                "Content-Type": "application/json",
            },
        )
        # Requests are retried with backoff for transient failures (rate limits,
        # 5xx). Auth and model-not-found errors are not retried because they fail
        # identically on every attempt.
        answer: dict[str, Any] | None = None
        for attempt in range(self.RETRIES + 1):
            try:
                with urllib.request.urlopen(req, timeout=180) as r:
                    answer = json.loads(r.read())
                break
            except urllib.error.HTTPError as e:
                detail = e.read()[:300].decode("utf-8", "replace")
                if e.code in (401, 403):
                    raise LLMConfigError(
                        f"HTTP {e.code} from {self.endpoint}: the endpoint rejected the "
                        f"token.\n  Check FW_TOKEN, a placeholder left in place looks "
                        f"exactly like this.\n  {detail}"
                    ) from e
                if e.code == 404:
                    raise LLMConfigError(
                        f"HTTP 404 from {self.endpoint}/v1/chat/completions.\n"
                        f"  Either the endpoint is not an OpenAI-compatible API, or it "
                        f"does not serve MODEL_ID={self.model!r}.\n  {detail}"
                    ) from e
                if e.code in (408, 409, 425, 429, 500, 502, 503, 504) \
                        and attempt < self.RETRIES:
                    self.retries += 1
                    time.sleep(min(2 ** attempt, 30) + random.random())
                    continue
                raise LLMError(f"HTTP {e.code}: {detail}") from e
            except Exception as e:  # network, timeout, malformed JSON
                if attempt < self.RETRIES:
                    self.retries += 1
                    time.sleep(min(2 ** attempt, 30) + random.random())
                    continue
                raise LLMError(f"{type(e).__name__}: {e}") from e
        if answer is None:
            raise LLMError("no answer after retries")

        self.calls += 1
        usage = answer.get("usage") or {}
        # Input and output tokens are tracked separately because they are priced
        # differently.
        self.tokens_in += usage.get("prompt_tokens", 0)
        self.tokens_out += usage.get("completion_tokens", 0)
        self.tokens_used += usage.get(
            "total_tokens",
            usage.get("prompt_tokens", 0) + usage.get("completion_tokens", 0),
        )
        choices = answer.get("choices") or []
        if not choices:
            raise LLMError("response had no choices")
        return choices[0].get("message") or {}

    @staticmethod
    def _index_from_text(text: str, n: int) -> int | None:
        """Attempts to extract a valid action index from a prose answer as a last resort."""
        import re

        for m in re.finditer(r"\[?(\d+)\]?", text):
            v = int(m.group(1))
            if 0 <= v < n:
                return v
        return None
